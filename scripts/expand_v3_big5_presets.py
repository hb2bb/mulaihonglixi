def main() -> None:
    text = PATH.read_text(encoding="utf-8")
    inserted = 0
    for heading, rows in EXPANSIONS:
        heading_marker = f"#### 4."
        heading_pos = text.find(heading)
        if heading_pos < 0:
            raise RuntimeError(f"missing facet heading: {heading}")
        next_heading = text.find("\n#### ", heading_pos + len(heading))
        next_group = text.find("\n### ", heading_pos + len(heading))
        candidates = [pos for pos in (next_heading, next_group) if pos >= 0]
        section_end = min(candidates) if candidates else len(text)
        section = text[heading_pos:section_end]
        if rows[0][0] in section:
            continue
        custom_pos = section.find("\n**自定义补充**")
        if custom_pos < 0:
            raise RuntimeError(f"missing custom marker for: {heading}")
        insert_at = heading_pos + custom_pos
        table_rows = "".join(f"| [ ] {low} | [ ] {high} |\n" for low, high in rows)
        text = text[:insert_at].rstrip("\n") + "\n" + table_rows + text[insert_at:]
        inserted += 1
    if inserted not in (0, 30):
        raise RuntimeError(f"expected to expand all 30 facets together, expanded {inserted}")
    PATH.write_text(text, encoding="utf-8")
    if inserted == 0:
        print("all 30 Big Five facet preset tables were already expanded")
    else:
        print("expanded all 30 Big Five facet preset tables")


if __name__ == "__main__":
    main()
