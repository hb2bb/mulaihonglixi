    dim_facets = OrderedDict()
    for item in questions:
        dim_facets.setdefault(item['dim'], OrderedDict()).setdefault(item['facet'], []).append(item)

    for dim, facets in dim_facets.items():
        lines.append(f'### {dim}')
        lines.append('')
        lines.append('| 子维度 | 题号 | 各选项对应等级 |')
        lines.append('|---|---|---|')
        for facet, items_list in facets.items():
            nums = ', '.join(str(i['id']) for i in items_list)
            level_strs = []
            for i in items_list:
                lm = i['level_map']
                parts = [f'{k}={v}' for k, v in sorted(lm.items())]
                level_strs.append(' / '.join(parts))
            level_str = '; '.join(level_strs)
            lines.append(f'| {facet} | {nums} | {level_str} |')
        lines.append('')

