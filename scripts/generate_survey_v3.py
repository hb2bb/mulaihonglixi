def generate():
    lines = []
    lines.append('# 通用性格调查问卷（ABCD 选项版）')
    lines.append('')
    lines.append('## 使用说明')
    lines.append('')
    lines.append(f'本问卷共 **{len(questions)}** 题，涵盖 6 大维度、72 个子维度。')
    lines.append('')
    lines.append('每题给出一个情境和四个选项（A/B/C/D），请选择**最符合你真实反应**的那一个。')
    lines.append('')
    lines.append('**注意：**')
    lines.append('- 没有对错之分，请尽量按真实情况作答')
    lines.append('- 如果两个选项都很接近，选更接近的那个')
    lines.append('- 每题只能选一个')
    lines.append('')
    lines.append('---')
    lines.append('')

    current_dim = None
    current_facet = None

    for item in questions:
        dim = item['dim']
        facet = item['facet']

        if dim != current_dim:
            if current_dim is not None:
                lines.append('')
                lines.append('---')
                lines.append('')
            lines.append(f'## {dim}')
            lines.append('')
            current_dim = dim
            current_facet = None

        if facet != current_facet:
            lines.append(f'### {facet}')
            lines.append('')
            current_facet = facet

        lines.append(f'**{item["id"]}.** {item["scenario"]}')
        lines.append('')
        for opt in item['opts']:
            lines.append(opt)
        lines.append('')
        lines.append('`A` `B` `C` `D`')
        lines.append('')

    return '\n'.join(lines)


