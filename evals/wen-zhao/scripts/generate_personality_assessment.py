def rotated_choices(options: dict[str, str], rotation: int) -> tuple[dict[str, str], dict[str, str]]:
    labels = ["A", "B", "C", "D"]
    roles = ["target", "acceptable", "opposite", "caricature"]
    ordered_roles = roles[rotation:] + roles[:rotation]
    choices = {label: options[role] for label, role in zip(labels, ordered_roles)}
    role_to_label = {role: label for label, role in zip(labels, ordered_roles)}
    return choices, role_to_label


def build_items() -> list[dict[str, object]]:
    items: list[dict[str, object]] = []
    for facet_index, facet in enumerate(FACETS, start=1):
        situations = facet["situations"]
        if len(situations) != 10:
            raise ValueError(f"{facet['id']} must contain exactly 10 situations")
        for item_index, scenario in enumerate(situations, start=1):
            choices, mapping = rotated_choices(
                facet["options"], (facet_index + item_index) % 4
            )
            items.append(
                {
                    "id": f"pa-{facet_index:02d}-{item_index:02d}",
                    "domain": facet["domain"],
                    "facet": facet["facet"],
                    "source_constructs": facet["constructs"],
                    "scenario": scenario,
                    "question": "在不添加新剧情的前提下，闻昭最可能采取哪一种反应？",
                    "choices": choices,
                    "expected": {
                        "best": mapping["target"],
                        "acceptable": [mapping["acceptable"]],
                        "incompatible": [mapping["opposite"], mapping["caricature"]],
                        "rationale": facet["rationale"],
                    },
                    "response_format": "只返回选项字母和一句不超过40字的理由。",
                }
            )
    return items


