def merge_expect(base: dict[str, Any], extra: dict[str, Any]) -> dict[str, Any]:
    merged = dict(base)
    for key, value in extra.items():
        if key in {"must_include_any", "must_not_include"}:
            merged[key] = list(dict.fromkeys([*merged.get(key, []), *value]))
        else:
            merged[key] = value
    return merged


def build_cases() -> list[dict[str, Any]]:
    cases: list[dict[str, Any]] = []
    for group_index, group in enumerate(GROUPS, start=1):
        if len(group["items"]) != 10:
            raise ValueError(f"{group['id']} must contain exactly 10 items")
        for item_index, raw_item in enumerate(group["items"], start=1):
            item = raw_item if isinstance(raw_item, dict) else {"turns": [raw_item]}
            expect = merge_expect(
                {**group["expect"], "must_not_include": GENERIC_BANNED},
                item.get("expect_add", {}),
            )
            cases.append(
                {
                    "id": f"ds-{group_index:02d}-{item_index:02d}",
                    "category": group["category"],
                    "turns": item["turns"],
                    "memory": item.get("memory", ""),
                    "live_state": item.get("live_state", ""),
                    "expect": expect,
                    "semantic_expect": item.get("semantic", group["semantic"]),
                }
            )
    return cases


def main() -> None:
    cases = build_cases()
    if len(cases) < 200:
        raise ValueError("dialogue set must contain at least 200 cases")
    if len({case["id"] for case in cases}) != len(cases):
        raise ValueError("duplicate case ids")
    OUTPUT.write_text(json.dumps(cases, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"generated {len(cases)} dialogue cases: {OUTPUT}")


if __name__ == "__main__":
    main()
